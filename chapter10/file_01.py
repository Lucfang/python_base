"""文件操做：前序知识"""

'''
文件的分类：
1.纯文本文件
Ⅰ 读取和存储时，要遵循某种【字符编码】规范(如：UTF-8等)进行编码和解码，最终以【二进制】的形式存储
Ⅱ 【纯文本文件】最终会呈现为：可以直接阅读的文本信息
Ⅲ 常见的【纯文本文件】有：.txt .py .md .html等
2.二进制文件
Ⅰ 读取和存储时，不涉及字符编码，会按照某种【文件格式规范】把内容转为【二进制】数据进行存储
Ⅱ 二进制文件需要由【能够识别其格式的软件】进行分析，最终的呈现形式多种多样(音频、视频、图像、幻灯片等)
Ⅲ 常见的二进制文件有：.mp3 .mp4 .doc .ppt .jpg .png等
'''

'''
绝对路径 vs 相对路径
1.绝对路径：从文件系统的【根目录】开始，完整描述文件或目录所在位置
2.相对路径：以当前【工作目录】为参照，描述目标文件或目录相对于它的位置
'''