"""条件表达式"""
# 表达式：执行后能得到值的代码，就是表达式(表达式最终会形成一个值，可以写在任何需要值的地方)
a1 = 3 + 5
a2 = 'abc' * 3
a3 = 5 > 3
a4 = 'y' in 'python'
a5 = len('hello')
print(a1, a2, a3, a4, a5)
# 条件表达式：根据条件的真假，在两个值中二选一的表达式(又称：三元表达式、三目运算符)
# 值1 if 条件 else 值2
# 使用场景：简单的二选一场景
age = 15
text = '成年' if age >= 18 else '未成年'
print(age, text)
