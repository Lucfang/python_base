"""浅拷贝  深拷贝"""
import copy

# 直接赋值：两个变量指向同一个对象，修改其中一个，就会影响另一个(互相影响)
# nums1 = [6, 7, 8, 9]
# nums2 = nums1
# nums2[3] = 99

# 浅拷贝：创建一个新的外层容器，但内容元素仍然引用原来的对象
# nums1 = [6, 7, 8, 9]
# nums2 = copy.copy(nums1)
# nums2[3] = 99

# 浅拷贝存在的问题：嵌套数据仍然是共享的，修改嵌套数据会相互影响
# nums1 = [6, 7, 8, 9, [70, 80, 90]]
# nums2 = copy.copy(nums1)
# nums2[4][2] = 88

# 深拷贝：创建一个新的外层容器，并对其内部所有的【可变对象】进行递归复制
'''
备注：
1.深拷贝可以彻底消除数据之间的相互影响
2.深拷贝只复制可变对象，遇到【不可变对象】不会复制，会直接引用
3.元组中如果只包含不可变对象，则深拷贝没有效果
'''
nums1 = [6, 7, 8, 9, [70, 80, 90, [60, 70]]]
nums2 = copy.deepcopy(nums1)
nums2[4][2] = 88
print(nums1)
print(nums2)
nums1[4][3][1] = 77
print(nums1)
print(nums2)
print(id(nums1[0]))
print(id(nums2[0]))

